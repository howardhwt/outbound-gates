"""Copy the quickstart project somewhere to try the send gate on it.

    python -m gates.quickstart [FOLDER]                    (default: ./outbound-gates-try)
    python -m gates.quickstart --prospect ADDR [FOLDER]    a try folder for your own prospect

With --prospect it makes a try folder for one real prospect instead: a
generated one-company CRM for the address's domain, clearly marked as not your
CRM, the neutral style, and no draft. /outbound-gates:start uses it. A
free-mail address is refused, because the domain is the only evidence of who
the company is.

The project has one fictional company, one fixture pricing page and one draft
with one number in it. The gate blocks the draft until the number's source is
recorded, then lets it through. Nothing goes over the network. The command
prints the three commands to run next, with this plugin's path filled in.
"""
from __future__ import annotations

import argparse
import json
import shlex
import shutil
import sys
from datetime import date
from pathlib import Path

PLUGIN_ROOT = Path(__file__).resolve().parents[1]
SOURCE = PLUGIN_ROOT / "demo" / "quickstart"
CONTACT = "dana@quickstart-co.example"
URL = "https://quickstart-co.example/pricing"
QUOTE = "Transcription is billed at $0.006 per audio minute"
TRY_NOTE = "TRY: generated by /outbound-gates:start, not your CRM; contact history not checked"
FREE_MAIL = frozenset({
    "gmail.com", "googlemail.com", "outlook.com", "hotmail.com", "live.com", "yahoo.com",
    "icloud.com", "me.com", "proton.me", "protonmail.com", "aol.com", "gmx.com",
})


class ProspectError(ValueError):
    """The address can't stand in for a company."""


def prospect_domain(address: str) -> str:
    """The company domain behind a prospect's work address."""
    address = (address or "").strip().lower()
    local, at, domain = address.partition("@")
    if not at or not local or "@" in domain or "." not in domain or any(c.isspace() for c in address):
        raise ProspectError(f"{address!r} is not one email address")
    domain = domain.rstrip(".")
    if domain in FREE_MAIL:
        raise ProspectError(f"{domain} is a free-mail provider, not the company: use a work address at the company")
    return domain


def make_try_folder(address: str, dest: Path, today: date | None = None) -> Path:
    """A new folder for a first catch on one real prospect. Never writes into an existing folder."""
    domain = prospect_domain(address)
    dest = dest.expanduser().resolve()
    if dest.exists():
        raise FileExistsError(f"{dest} already exists; pick a new folder")
    gates = dest / ".gates"
    gates.mkdir(parents=True)
    config = {"_comment": TRY_NOTE, "crm_path": "crm.json"}
    company = {
        "domain": domain, "alt_domains": [], "name": domain, "status": "NEW", "lane": "try", "segment": "try",
        "date_contacted": None, "date_replied": None,
        "notes": [{"date": (today or date.today()).isoformat(), "text": TRY_NOTE}], "tasks": [], "deals": [],
    }
    (gates / "config.json").write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
    (gates / "style.json").write_text("{}\n", encoding="utf-8")
    (dest / "crm.json").write_text(json.dumps({"_comment": TRY_NOTE, "companies": [company]}, indent=2) + "\n",
                                   encoding="utf-8")
    return dest


def prospect_commands(dest: Path, address: str) -> list[str]:
    """Check, record (fill in URL, QUOTE and VALUE) and check again, for a try folder."""
    q = shlex.quote
    py = f"PYTHONPATH={q(str(PLUGIN_ROOT))} python3 -m"
    to = q(address.strip().lower())
    check = f"{py} gates.evaluate {q(str(dest / 'draft.txt'))} --project {q(str(dest))} --to {to}"
    record = (f"{py} gates.evidence record --gates-home {q(str(dest / '.gates'))} --contact {to}"
              " --url URL --quote 'QUOTE' --value VALUE")
    return [check, record, check]


def copy_to(dest: Path) -> Path:
    """Copy the project to dest (which must not exist) and return its absolute path."""
    dest = dest.expanduser().resolve()
    if dest.exists():
        raise FileExistsError(f"{dest} already exists; pick a new folder")
    shutil.copytree(SOURCE, dest)
    (dest / "gates").rename(dest / ".gates")
    return dest


def next_commands(dest: Path) -> list[str]:
    q = shlex.quote
    py = f"PYTHONPATH={q(str(PLUGIN_ROOT))} python3 -m"
    check = f"{py} gates.evaluate {q(str(dest / 'draft.txt'))} --project {q(str(dest))} --to {CONTACT}"
    record = (f"{py} gates.evidence record --gates-home {q(str(dest / '.gates'))} --contact {CONTACT}"
              f" --url {URL} --quote {q(QUOTE)} --value '$0.006'")
    return [check, record, check]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Copy the quickstart project to try the send gate.")
    parser.add_argument("folder", nargs="?", default="outbound-gates-try", help="where to put it (must not exist)")
    parser.add_argument("--prospect", metavar="ADDR", help="make a try folder for this prospect's work address instead")
    args = parser.parse_args(argv)
    if args.prospect:
        try:
            dest = make_try_folder(args.prospect, Path(args.folder))
        except ProspectError as err:
            print(f"refused: {err}", file=sys.stderr)
            return 1
        except (FileExistsError, OSError) as err:
            print(f"error: {err}", file=sys.stderr)
            return 2
        check, record, again = prospect_commands(dest, args.prospect)
        print(f"Try folder ready in {dest}")
        print(f"  The CRM here is generated for {prospect_domain(args.prospect)} only. {TRY_NOTE}.\n")
        print(f"1. Write the email to {dest / 'draft.txt'}, then check it:")
        print(f"   {check}\n")
        print("2. Record each number's source: the exact sentence on the company's own page.")
        print(f"   {record}\n")
        print("3. Check again.")
        print(f"   {again}")
        return 0
    try:
        dest = copy_to(Path(args.folder))
    except (FileExistsError, OSError) as err:
        print(f"error: {err}", file=sys.stderr)
        return 2
    check, record, again = next_commands(dest)
    print(f"Quickstart project ready in {dest}\n")
    print("1. Check the draft. It is BLOCKED: $0.006 has no recorded source.")
    print(f"   {check}\n")
    print("2. Record the source: the exact sentence on the company's pricing page.")
    print(f"   {record}\n")
    print("3. Check again. It passes.")
    print(f"   {again}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
